'use strict';
const assert=require('node:assert/strict');
const {chromium}=require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const base=process.env.TEST_BASE_URL;
const journal={version:1,data_kind:'manual',entries:[{id:'manual-session-a',date:'2026-10-09',country_code:'CN',province_code:'310000',city:'上海',store:'合成私人手账A',foods:['咖啡'],source:'manual',confirmed:true,note:'浏览器会话验收'}]};

async function main(){
  const browser=await chromium.launch({headless:true,...(process.env.BROWSER_CHANNEL?{channel:process.env.BROWSER_CHANNEL}:{})});
  const errors=[];
  try {
    const a=await browser.newContext({viewport:{width:390,height:844}});
    const b=await browser.newContext({viewport:{width:390,height:844}});
    const page=await a.newPage();const other=await b.newPage();
    for(const p of [page,other])p.on('pageerror',e=>errors.push(e.message));
    await page.goto(base);await other.goto(base);
    await page.locator('#open-connect').click();
    assert.equal(await page.locator('#remember-field').isVisible(),true);
    assert.equal(await page.locator('#connect-remember').isChecked(),true);
    await page.locator('#connect-manual').evaluate(details => { details.open = true; });
    await page.locator('#connect-token').fill('fixture-browser-a');
    await page.locator('#connect-submit').click();
    await page.locator('#connect-dialog').waitFor({state:'hidden'});
    await page.locator('#sync-progress').filter({hasText:/已(?:自动)?整理/}).waitFor();
    await page.waitForFunction(()=>!document.getElementById('sync-orders').disabled);
    await page.locator('#disconnect-mcd').waitFor({state:'visible'});
    assert.equal(await page.locator('#connect-token').inputValue(),'');
    assert.equal(await other.locator('#disconnect-mcd').isVisible(),false);
    await page.locator('#import-file').setInputFiles({name:'synthetic-session.json',mimeType:'application/json',buffer:Buffer.from(JSON.stringify(journal))});
    await page.locator('#count-visits').filter({hasText:'2'}).waitFor();
    await page.reload();
    await page.locator('#disconnect-mcd').waitFor({state:'visible'});
    assert.equal(await page.locator('#count-visits').innerText(),'2');
    assert.match(await page.locator('#connection-state').innerText(),/下次打开/);
    const cookies=await a.cookies();
    assert.equal(cookies.find(c=>c.name==='mcd_session').httpOnly,true);
    assert.equal(cookies.find(c=>c.name==='mcd_session').sameSite,'Strict');
    assert.ok(cookies.find(c=>c.name==='mcd_session').expires>Date.now()/1000);
    const visible=await page.evaluate(()=>({cookie:document.cookie,storage:JSON.stringify({...localStorage}),html:document.documentElement.outerHTML}));
    assert.doesNotMatch(visible.cookie,/mcd_session/);
    assert.doesNotMatch(visible.storage,/fixture-browser-a/);
    assert.doesNotMatch(visible.html,/fixture-browser-a/);
    await page.locator('#sync-orders').click();
    await page.locator('#sync-progress').filter({hasText:/已(?:自动)?整理|本次没有/}).waitFor();
    const orders=await page.evaluate(()=>fetch('/api/synced-orders').then(r=>r.json()));
    assert.equal(orders.entries[0].id,'candidate-a');
    assert.equal(await other.evaluate(()=>fetch('/api/synced-orders').then(r=>r.status)),401);
    await page.locator('#open-connect').click();
    await page.locator('#connect-manual').evaluate(details => { details.open = true; });
    await page.locator('#connect-token').fill('fixture-browser-b');
    await page.locator('#connect-submit').click();
    await page.locator('#connect-dialog').waitFor({state:'hidden'});
    await page.locator('#sync-progress').filter({hasText:/已(?:自动)?整理/}).waitFor();
    await page.waitForFunction(()=>!document.getElementById('sync-orders').disabled);
    await page.locator('#count-visits').filter({hasText:'1'}).waitFor();
    assert.equal(await page.locator('#count-visits').innerText(),'1','another connection has its own automatically imported journal');
    await page.locator('#open-connect').click();
    await page.locator('#connect-manual').evaluate(details => { details.open = true; });
    await page.locator('#connect-token').fill('fixture-browser-a');
    await page.locator('#connect-submit').click();
    await page.locator('#connect-dialog').waitFor({state:'hidden'});
    await page.locator('#sync-progress').filter({hasText:/已(?:自动)?整理/}).waitFor();
    await page.waitForFunction(()=>!document.getElementById('sync-orders').disabled);
    await page.locator('#count-visits').filter({hasText:'2'}).waitFor();
    assert.equal(await page.locator('#count-visits').innerText(),'2','returning to same Token restores its journal and synced orders');
    const rememberedState=await a.storageState();
    const resumed=await browser.newContext({storageState:rememberedState});
    const again=await resumed.newPage();
    await again.goto(base);await again.locator('#disconnect-mcd').waitFor({state:'visible'});
    assert.equal(await again.locator('#count-visits').innerText(),'2');
    assert.equal(cookies.find(c=>c.name==='mcd_resume').httpOnly,true);
    assert.doesNotMatch(visible.cookie,/mcd_resume/);
    const beforeReset=await page.evaluate(()=>fetch('/api/health').then(r=>r.json()));
    assert.equal(beforeReset.capabilities.durable_remember_session,true);
    await page.evaluate(()=>fetch('/__fixture_reset',{method:'POST'}));
    await page.reload();await page.locator('#disconnect-mcd').waitFor({state:'visible'});
    const recovered=await page.evaluate(()=>fetch('/api/health').then(r=>r.json()));
    assert.equal(recovered.account_id,beforeReset.account_id);
    assert.equal(await page.locator('#count-visits').innerText(),'2');
    assert.equal(await page.evaluate(()=>fetch('/api/synced-orders').then(r=>r.status)),404,'order cache stays off the recovery cookie');
    assert.equal(await other.evaluate(()=>fetch('/api/health').then(r=>r.json())).then(r=>r.connected),false);
    await page.locator('#sync-orders').click();
    await page.locator('#sync-progress').filter({hasText:/已(?:自动)?整理|本次没有/}).waitFor();
    assert.equal(await page.locator('#count-visits').innerText(),'2','resync after losing server disk does not duplicate browser journal');
    await other.locator('#open-connect').click();
    await other.locator('#connect-manual').evaluate(details => { details.open = true; });
    await other.locator('#connect-token').fill('fixture-browser-b');
    await other.locator('#connect-submit').click();
    await other.locator('#connect-dialog').waitFor({state:'hidden'});
    await other.locator('#sync-progress').filter({hasText:/已(?:自动)?整理/}).waitFor();
    await other.waitForFunction(()=>!document.getElementById('sync-orders').disabled);
    await page.locator('#disconnect-mcd').click();
    await page.locator('#disconnect-mcd').waitFor({state:'hidden'});
    assert.equal(await page.locator('#count-visits').innerText(),'2');
    await other.reload();await other.locator('#disconnect-mcd').waitFor({state:'visible'});
    assert.equal(await page.evaluate(()=>fetch('/api/synced-orders').then(r=>r.status)),401);
    assert.deepEqual(errors,[]);
    console.log('PASS: real HTTP Cookie login, HttpOnly recovery after complete server-directory loss, preserved browser journal, deduplicated resync, refresh/browser restoration, isolated users/orders, account switching and logout. Synthetic upstream only.');
  } finally {await browser.close();}
}
main().catch(error=>{console.error(error);process.exitCode=1;});
